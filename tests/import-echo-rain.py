"""Preserve the six frozen buildLevel rain seeds without changing scene exports."""
import importlib.util,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('scene_import',Path(__file__).with_name('import-store.py'))
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
data=json.loads((root/'validation/transparency/source-rain-seeds.json').read_text())
assert len(data)==6 and all(len(level)==600 for level in data)
assert all(len(p)==3 for level in data for p in level)
(root/'scripts/game/data/EchoRainSeeds.lua').write_text('-- Generated by tests/import-echo-rain.py from frozen buildLevel, seed 0x6a316e84.\nreturn '+m.lua(data)+'\n')
print('Imported 6 × 600 frozen rain seeds')
