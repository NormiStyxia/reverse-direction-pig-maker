function constant(file, name, nextMarker) {
  const text = read(file).toString();
  const start = text.indexOf(`export const ${name} = `);
  if (start < 0) throw new Error(`Missing ${name}`);
  const end = text.indexOf(nextMarker, start);
  if (end < 0) throw new Error(`Missing terminator for ${name}`);
  const declaration = text.slice(start, end).replace('export const ', 'const ');
  return vm.runInNewContext(`${declaration}
JSON.stringify(${name})`, {}, {timeout: 1000});
}
function lua(value) {
  if (value === null) return 'nil';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return '{' + value.map(lua).join(',') + '}';
  return '{' + Object.entries(value).map(([k,v]) => `[${lua(k)}]=${lua(v)}`).join(',') + '}';
}
