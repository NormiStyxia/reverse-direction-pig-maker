"""Convert source Float32 samples to native PCM16 WAV; validate no clipping."""
import json,hashlib,wave
from pathlib import Path
import numpy as np
root=Path(__file__).resolve().parents[1];rows=[];catalog=json.loads((root/'tests/audio-clips.json').read_text())
receipt=json.loads((root/'validation/audio/source/receipt.json').read_text())
for c in receipt['clips']:
 src=root/'validation/audio/source'/(c['id']+'.f32');a=np.fromfile(src,dtype='<f4');assert len(a)==c['frames']
 assert np.isfinite(a).all() and np.abs(a).max()<1 and np.abs(a).max()>0
 pcm=np.round(a.astype(float)*32767).astype('<i2');error=abs(pcm.astype(float)/32767-a)
 assert error.max()<=.5/32767+1e-10
 out=root/'assets/audio/source'/(c['id']+'.wav')
 with wave.open(str(out),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(c['rate']);w.writeframes(pcm.tobytes())
 rows.append(dict(id=c['id'],frames=len(a),peak=float(abs(a).max()),rms=float(np.sqrt(np.mean(a*a))),maxQuantizationError=float(error.max()),sha256=hashlib.sha256(out.read_bytes()).hexdigest()))
lines=['-- Generated by tests/prepare-audio.py from the frozen StoreAudio export.','return {']
for c in catalog:lines.append('    ["'+c['id']+'"]="audio/source/'+c['id']+'.wav",')
lines.append('}');(root/'scripts/game/data/AudioClips.lua').write_text(chr(10).join(lines)+chr(10))
report=dict(result='PASS',sourceSha256=hashlib.sha256((root/'reference/h5-source/src/store-audio.js').read_bytes()).hexdigest(),clips=rows,scope='source OfflineAudioContext to PCM16 waveform fidelity; not native playback or all game audio')
(root/'docs/migration/audio-assets-report.json').write_text(json.dumps(report,indent=2)+chr(10));print('PCM16 PASS:',len(rows),'clips; no clipping; max error <= 0.5/32767')
